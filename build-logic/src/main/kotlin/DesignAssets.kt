object DesignAssets {
    const val LOCK_PATH: String = "design/putio-design.lock.json"
    const val GENERATED_MARKER: String = "Generated by ./gradlew syncDesignAssets; do not edit."
    const val TOKENS_PATH: String = "design/tokens.dtcg.json"
    const val WORDMARK_PATH: String = "core/design/src/main/res/drawable/putio_wordmark.xml"
    const val MONOCHROME_ICON_PATH: String = "mobile/src/main/res/drawable/putio_launcher_monochrome.xml"
    const val LAUNCHER_ICON_FILE: String = "putio_icon.png"
    const val LAUNCHER_ART_FILE: String = "putio_launcher_art.png"

    val PRODUCTION_RES_DIRS: List<String> = listOf("core/design/src/main/res")
    val NIGHTLY_RES_DIRS: List<String> = listOf("mobile/src/nightly/res", "tv/src/nightly/res")
    val DEV_RES_DIRS: List<String> = listOf("mobile/src/debug/res")
    val PRODUCTION_ART_RES_DIRS: List<String> = listOf("mobile/src/main/res")
    val NIGHTLY_ART_RES_DIRS: List<String> = listOf("mobile/src/nightly/res")
    val DEV_ART_RES_DIRS: List<String> = listOf("mobile/src/debug/res")
    val LAUNCHER_ICON_DENSITIES: Map<String, Int> =
        mapOf("mdpi" to 48, "hdpi" to 72, "xhdpi" to 96, "xxhdpi" to 144, "xxxhdpi" to 192)
    val LAUNCHER_ART_DENSITIES: Map<String, Int> =
        mapOf("mdpi" to 72, "hdpi" to 108, "xhdpi" to 144, "xxhdpi" to 216, "xxxhdpi" to 288)

    val OUTPUT_PATHS: List<String> =
        listOf(TOKENS_PATH, WORDMARK_PATH, MONOCHROME_ICON_PATH) +
            launcherPaths(PRODUCTION_RES_DIRS + NIGHTLY_RES_DIRS + DEV_RES_DIRS, LAUNCHER_ICON_DENSITIES, LAUNCHER_ICON_FILE) +
            launcherPaths(PRODUCTION_ART_RES_DIRS + NIGHTLY_ART_RES_DIRS + DEV_ART_RES_DIRS, LAUNCHER_ART_DENSITIES, LAUNCHER_ART_FILE)

    private const val PACKAGE_NAME = "@putdotio/design"
    private const val INTEGRITY_PREFIX = "sha512-"
    private const val SHA512_BYTES = 64
    private const val SVG_NAMESPACE = "http://www.w3.org/2000/svg"
    private const val XMLNS_NAMESPACE = "http://www.w3.org/2000/xmlns/"
    private val SVG_FILLS = mapOf("white" to "#FFFFFFFF")
    private val PATH_ATTRIBUTES = setOf("d", "fill", "fill-rule", "clip-rule")
    private val HEX_COLOR = Regex("#([0-9A-Fa-f]{6})")
    private val NUMBER = Regex("-?[0-9]+(?:\\.[0-9]+)?")
    private val SHA256 = Regex("[0-9a-f]{64}")
    private val VERSION = Regex("[0-9]+\\.[0-9]+\\.[0-9]+")
    private val ROOT_FIELDS = setOf(
        "schemaVersion", "package", "tokens", "productionIcon", "nightlyIcon", "devIcon", "wordmark", "monochromeIcon",
    )

    data class Package(val name: String, val version: String, val tarball: String, val integrity: String)

    data class Asset(val asset: String, val sourceSha256: String)

    data class IconOutput(
        val density: String,
        val size: Int,
        val sha256: String,
        val resDirs: List<String>,
        val fileName: String,
    ) {
        val paths: List<String> get() = resDirs.map { "$it/drawable-$density/$fileName" }
    }

    data class LauncherIcon(val source: Asset, val outputs: List<IconOutput>, val artOutputs: List<IconOutput>) {
        val allOutputs: List<IconOutput> get() = outputs + artOutputs
    }

    data class Lock(
        val pkg: Package,
        val tokens: Asset,
        val productionIcon: LauncherIcon,
        val nightlyIcon: LauncherIcon,
        val devIcon: LauncherIcon,
        val wordmark: Asset,
        val wordmarkOutputSha256: String,
        val monochromeIcon: Asset,
        val monochromeIconOutputSha256: String,
    ) {
        val launcherIcons: List<LauncherIcon> get() = listOf(productionIcon, nightlyIcon, devIcon)

        val assets: Set<String>
            get() = (listOf(tokens) + launcherIcons.map(LauncherIcon::source) + listOf(wordmark, monochromeIcon))
                .map(Asset::asset).toSet()
    }

    fun parseLock(json: String): Lock {
        val document = try {
            Json.parseToJsonElement(json)
        } catch (error: SerializationException) {
            fail("cannot read $LOCK_PATH: ${error.message}")
        }
        LockJson.duplicateKey(json)?.let { fail("lock contains duplicate key '$it'") }
        val root = document.objectWithKeys("lock", ROOT_FIELDS)
        val schemaVersion = root["schemaVersion"] as? JsonPrimitive
        if (schemaVersion == null || schemaVersion.isString || schemaVersion.content != "1") {
            fail("lock must use schemaVersion 1")
        }
        val (tokens, _) = asset(root.getValue("tokens"), "tokens")
        val (wordmark, rawWordmark) = asset(root.getValue("wordmark"), "wordmark", setOf("outputSha256"))
        val (monochromeIcon, rawMonochromeIcon) =
            asset(root.getValue("monochromeIcon"), "monochromeIcon", setOf("outputSha256"))
        return Lock(
            pkg = pkg(root.getValue("package")),
            tokens = tokens,
            productionIcon = launcherIcon(
                root.getValue("productionIcon"), "productionIcon", PRODUCTION_RES_DIRS, PRODUCTION_ART_RES_DIRS,
            ),
            nightlyIcon = launcherIcon(root.getValue("nightlyIcon"), "nightlyIcon", NIGHTLY_RES_DIRS, NIGHTLY_ART_RES_DIRS),
            devIcon = launcherIcon(root.getValue("devIcon"), "devIcon", DEV_RES_DIRS, DEV_ART_RES_DIRS),
            wordmark = wordmark,
            wordmarkOutputSha256 = rawWordmark.sha256("outputSha256", "wordmark.outputSha256"),
            monochromeIcon = monochromeIcon,
            monochromeIconOutputSha256 = rawMonochromeIcon.sha256("outputSha256", "monochromeIcon.outputSha256"),
        )
    }

    fun lockedOutputs(lock: Lock): List<Pair<String, String>> =
        listOf(TOKENS_PATH to lock.tokens.sourceSha256) +
            lock.launcherIcons.flatMap { icon ->
                icon.allOutputs.flatMap { output -> output.paths.map { it to output.sha256 } }
            } +
            listOf(WORDMARK_PATH to lock.wordmarkOutputSha256, MONOCHROME_ICON_PATH to lock.monochromeIconOutputSha256)

    fun filesByPath(root: File, files: Iterable<File>): Map<String, File> =
        files.filter(File::isFile).associateBy { it.relativeTo(root).invariantSeparatorsPath }

    fun driftFailures(lock: Lock, files: Map<String, File>): List<String> =
        lockedOutputs(lock).mapNotNull { (path, expected) ->
            val file = files[path] ?: return@mapNotNull "missing $path"
            if (digestEquals(sha256(file.readBytes()), expected)) null else "drifted $path"
        }

    fun check(lock: Lock, files: Map<String, File>): String {
        val failures = driftFailures(lock, files)
        if (failures.isNotEmpty()) fail("design asset drift detected:\n  " + failures.joinToString("\n  "))
        return "Design asset drift check passed (${lockedOutputs(lock).size} files, ${lock.pkg.name}@${lock.pkg.version})"
    }

    fun verifyArchive(pkg: Package, archive: ByteArray) {
        val actual = Base64.getEncoder().encodeToString(MessageDigest.getInstance("SHA-512").digest(archive))
        if (!digestEquals(actual, pkg.integrity.removePrefix(INTEGRITY_PREFIX))) {
            fail("downloaded package does not match locked sha512 SRI")
        }
    }

    fun sync(
        lock: Lock,
        root: File,
        archive: ByteArray,
        unpack: (ByteArray) -> Map<String, ByteArray>,
        log: (String) -> Unit,
        renderLauncher: (ByteArray, LauncherIcon) -> Map<String, ByteArray> = ::renderLauncherIcon,
    ) {
        verifyArchive(lock.pkg, archive)
        val files = unpack(archive)
        val sources = (listOf(lock.tokens) + lock.launcherIcons.map(LauncherIcon::source) + listOf(lock.wordmark, lock.monochromeIcon))
            .map { it to (files[it.asset] ?: fail("locked package is missing ${it.asset}")) }
        val mismatches = sources.mapNotNull { (asset, data) ->
            val actual = sha256(data)
            if (digestEquals(actual, asset.sourceSha256)) null else "${asset.asset} is $actual, locked ${asset.sourceSha256}"
        }.toMutableList()
        val source = sources.toMap()
        val outputs = linkedMapOf(TOKENS_PATH to source.getValue(lock.tokens))
        lock.launcherIcons.forEach { outputs += renderLauncher(source.getValue(it.source), it) }
        outputs[WORDMARK_PATH] = renderWordmark(source.getValue(lock.wordmark), lock.wordmark.asset, lock.pkg.version)
        outputs[MONOCHROME_ICON_PATH] =
            renderMonochromeIcon(source.getValue(lock.monochromeIcon), lock.monochromeIcon.asset, lock.pkg.version)
        mismatches += lockedOutputs(lock).drop(1).mapNotNull { (path, expected) ->
            val actual = sha256(outputs.getValue(path))
            if (digestEquals(actual, expected)) null else "generated $path is $actual, locked $expected"
        }
        if (mismatches.isNotEmpty()) fail("unlocked design assets; nothing written:\n  " + mismatches.joinToString("\n  "))
        outputs.forEach { (path, data) ->
            val target = root.resolve(path)
            target.parentFile.mkdirs()
            target.writeBytes(data)
            log("wrote $path")
        }
    }

    fun renderLauncherIcon(source: ByteArray, icon: LauncherIcon): Map<String, ByteArray> {
        val image = try {
            ImageIO.read(ByteArrayInputStream(source))
        } catch (error: IOException) {
            fail("${icon.source.asset} is not a readable image: ${error.message}")
        } ?: fail("${icon.source.asset} is not a readable image")
        return icon.allOutputs.flatMap { output ->
            val data = resample(image, output.size)
            output.paths.map { it to data }
        }.toMap()
    }

    fun renderWordmark(source: ByteArray, asset: String, version: String): ByteArray =
        renderVector(source, asset, "put.io retro wordmark, @putdotio/design v$version $asset", 4.0)

    fun renderMonochromeIcon(source: ByteArray, asset: String, version: String): ByteArray =
        renderVector(source, asset, "put.io monochrome launcher mark, @putdotio/design v$version $asset", 1.0, "white")

    fun sha256(bytes: ByteArray): String =
        MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { "%02x".format(it) }

    private fun resample(image: BufferedImage, size: Int): ByteArray {
        val pixels = IntArray(size * size)
        val scaled = FilteredImageSource(image.source, AreaAveragingScaleFilter(size, size))
        if (!PixelGrabber(scaled, 0, 0, size, size, pixels, 0, size).grabPixels()) fail("resampling to ${size}px failed")
        val output = BufferedImage(size, size, BufferedImage.TYPE_INT_ARGB)
        output.setRGB(0, 0, size, size, pixels, 0, size)
        return ByteArrayOutputStream().also { ImageIO.write(output, "png", it) }.toByteArray()
    }

    private fun renderVector(
        source: ByteArray,
        asset: String,
        header: String,
        unitsPerDp: Double,
        defaultFill: String? = null,
    ): ByteArray {
        val root = parseSvg(source, asset)
        val viewBox = root.getAttribute("viewBox").trim().split(Regex("\\s+"))
        if (viewBox.size != 4 || !viewBox.all(NUMBER::matches)) fail("$asset needs a numeric viewBox")
        val (minX, minY, width, height) = viewBox
        val paths = root.childNodes.let { nodes -> (0 until nodes.length).map(nodes::item) }
            .filterIsInstance<Element>()
            .map { element ->
                if (element.namespaceURI != SVG_NAMESPACE || element.localName != "path") {
                    fail("$asset contains unsupported element ${clarkName(element)}")
                }
                val attributes = element.attributes.let { list -> (0 until list.length).map(list::item) }
                    .filter { it.namespaceURI != XMLNS_NAMESPACE }
                    .associate { clarkName(it) to it.nodeValue }
                val fill = attributes["fill"] ?: defaultFill
                if (!PATH_ATTRIBUTES.containsAll(attributes.keys) || "d" !in attributes || fill == null) {
                    fail("$asset has a path the converter cannot model")
                }
                val fillRule = attributes["fill-rule"] ?: "nonzero"
                if (fillRule != "nonzero" && fillRule != "evenodd") fail("$asset uses unsupported fill-rule '$fillRule'")
                val fillType = if (fillRule == "evenodd") "\n            android:fillType=\"evenOdd\"" else ""
                "        <path\n" +
                    "            android:fillColor=\"${androidColor(fill, asset)}\"$fillType\n" +
                    "            android:pathData=\"${escapeAttribute(attributes.getValue("d"))}\" />"
            }
        if (paths.isEmpty()) fail("$asset contains no path data")
        return (
            "<!-- $header. $GENERATED_MARKER -->\n" +
                "<vector xmlns:android=\"http://schemas.android.com/apk/res/android\"\n" +
                "    android:width=\"${formatG(width.toDouble() / unitsPerDp)}dp\"\n" +
                "    android:height=\"${formatG(height.toDouble() / unitsPerDp)}dp\"\n" +
                "    android:viewportWidth=\"$width\"\n" +
                "    android:viewportHeight=\"$height\">\n" +
                "    <group\n" +
                "        android:translateX=\"${formatG(translation(minX))}\"\n" +
                "        android:translateY=\"${formatG(translation(minY))}\">\n" +
                paths.joinToString("\n") +
                "\n    </group>\n</vector>\n"
            ).toByteArray(Charsets.UTF_8)
    }

    private fun parseSvg(source: ByteArray, asset: String): Element {
        val factory = DocumentBuilderFactory.newInstance().apply {
            isNamespaceAware = true
            setFeature(XMLConstants.FEATURE_SECURE_PROCESSING, true)
            setFeature("http://xml.org/sax/features/external-general-entities", false)
            setFeature("http://xml.org/sax/features/external-parameter-entities", false)
            setFeature("http://apache.org/xml/features/nonvalidating/load-external-dtd", false)
        }
        return try {
            factory.newDocumentBuilder().parse(ByteArrayInputStream(source)).documentElement
        } catch (error: org.xml.sax.SAXException) {
            fail("$asset is invalid XML: ${error.message}")
        }
    }

    private fun escapeAttribute(value: String): String =
        value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\"", "&quot;")

    private fun clarkName(node: Node): String {
        val name = node.localName ?: node.nodeName
        return node.namespaceURI?.let { "{$it}$name" } ?: name
    }

    private fun translation(min: String): Double = min.toDouble().let { if (it == 0.0) 0.0 else -it }

    private fun androidColor(fill: String, asset: String): String =
        SVG_FILLS[fill]
            ?: HEX_COLOR.matchEntire(fill)?.let { "#FF${it.groupValues[1].uppercase()}" }
            ?: fail("$asset uses unsupported fill '$fill'")

    private fun formatG(value: Double): String {
        if (value == 0.0) return if (1.0 / value < 0) "-0" else "0"
        val rounded = BigDecimal(value).round(MathContext(6, RoundingMode.HALF_EVEN))
        val exponent = rounded.precision() - rounded.scale() - 1
        if (exponent in -4..5) return rounded.stripTrailingZeros().toPlainString()
        val mantissa = rounded.movePointLeft(exponent).stripTrailingZeros().toPlainString()
        return "${mantissa}e${if (exponent < 0) "-" else "+"}${"%02d".format(abs(exponent))}"
    }

    private fun launcherPaths(resDirs: List<String>, densities: Map<String, Int>, fileName: String): List<String> =
        resDirs.flatMap { res -> densities.keys.map { "$res/drawable-$it/$fileName" } }

    private fun pkg(value: JsonElement): Package {
        val raw = value.objectWithKeys("package", setOf("name", "version", "tarball", "integrity"))
        val pkg = Package(
            name = raw.string("name", "package.name"),
            version = raw.string("version", "package.version"),
            tarball = raw.string("tarball", "package.tarball"),
            integrity = raw.string("integrity", "package.integrity"),
        )
        if (pkg.name != PACKAGE_NAME || !VERSION.matches(pkg.version)) {
            fail("package must be $PACKAGE_NAME at an exact x.y.z version")
        }
        if (pkg.tarball != "https://registry.npmjs.org/@putdotio/design/-/design-${pkg.version}.tgz") {
            fail("package.tarball does not match the locked version")
        }
        if (!pkg.integrity.startsWith(INTEGRITY_PREFIX)) fail("package.integrity must use sha512 SRI")
        val digest = pkg.integrity.removePrefix(INTEGRITY_PREFIX)
        val decoded = try {
            if (digest.length % 4 != 0) throw IllegalArgumentException("incorrect padding")
            Base64.getDecoder().decode(digest)
        } catch (_: IllegalArgumentException) {
            fail("package.integrity must contain valid base64")
        }
        if (decoded.size != SHA512_BYTES) fail("package.integrity must contain a SHA-512 digest")
        return pkg
    }

    private fun asset(value: JsonElement, field: String, extra: Set<String> = emptySet()): Pair<Asset, JsonObject> {
        val raw = value.objectWithKeys(field, setOf("asset", "sourceSha256") + extra)
        val asset = raw.string("asset", "$field.asset")
        if (asset.startsWith("/") || asset.split('/').any { it == ".." }) {
            fail("$field.asset must be a relative package path")
        }
        return Asset(asset, raw.sha256("sourceSha256", "$field.sourceSha256")) to raw
    }

    private fun launcherIcon(value: JsonElement, field: String, resDirs: List<String>, artResDirs: List<String>): LauncherIcon {
        val (source, raw) = asset(value, field, setOf("outputs", "artOutputs"))
        return LauncherIcon(
            source,
            iconOutputs(raw.getValue("outputs"), "$field.outputs", LAUNCHER_ICON_DENSITIES, resDirs, LAUNCHER_ICON_FILE),
            iconOutputs(raw.getValue("artOutputs"), "$field.artOutputs", LAUNCHER_ART_DENSITIES, artResDirs, LAUNCHER_ART_FILE),
        )
    }

    private fun iconOutputs(
        value: JsonElement,
        field: String,
        densities: Map<String, Int>,
        resDirs: List<String>,
        fileName: String,
    ): List<IconOutput> {
        val array = value as? JsonArray ?: fail("$field must be an array")
        val outputs = array.mapIndexed { index, rawOutput ->
            val outputField = "$field[$index]"
            val raw = rawOutput.objectWithKeys(outputField, setOf("density", "size", "sha256"))
            val density = raw.string("density", "$outputField.density")
            val size = (raw["size"] as? JsonPrimitive)?.takeUnless { it.isString }?.content?.toIntOrNull()
            if (size == null || densities[density] != size) {
                fail("$outputField must pair a launcher density with its icon size")
            }
            IconOutput(density, size, raw.sha256("sha256", "$outputField.sha256"), resDirs, fileName)
        }
        if (outputs.map(IconOutput::density).sorted() != densities.keys.sorted()) {
            fail("$field must list each launcher density exactly once")
        }
        return outputs
    }

    private fun JsonElement.objectWithKeys(field: String, keys: Set<String>): JsonObject =
        (this as? JsonObject)?.takeIf { it.keys == keys } ?: fail("$field fields do not match the schema")

    private fun JsonObject.string(key: String, field: String): String =
        (this[key] as? JsonPrimitive)?.takeIf { it.isString && it.content.isNotEmpty() }?.content
            ?: fail("$field must be a non-empty string")

    private fun JsonObject.sha256(key: String, field: String): String =
        string(key, field).also { if (!SHA256.matches(it)) fail("$field must be a lowercase SHA-256 digest") }

    private fun digestEquals(actual: String, expected: String): Boolean =
        MessageDigest.isEqual(actual.toByteArray(), expected.toByteArray())

    private fun fail(message: String): Nothing = throw GradleException("design-assets: $message")
}
