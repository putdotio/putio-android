import java.io.ByteArrayInputStream
import java.io.File
import java.security.MessageDigest
import java.util.Base64
import javax.xml.XMLConstants
import javax.xml.parsers.DocumentBuilderFactory
import kotlinx.serialization.SerializationException
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import org.gradle.api.GradleException
import org.w3c.dom.Element

object PhosphorIcons {
    const val GENERATED_MARKER: String = "Generated by ./gradlew generateIcons; do not edit."

    val DRAWABLE_PATTERNS: List<String> =
        listOf("*/src/*/res/drawable/ic_ph_*.xml", "*/*/src/*/res/drawable/ic_ph_*.xml")

    private const val PACKAGE_NAME = "@phosphor-icons/core"
    private const val INTEGRITY_PREFIX = "sha512-"
    private const val SHA512_BYTES = 64
    private val RES_DIRS = setOf("core/design/src/main/res", "mobile/src/main/res", "tv/src/main/res")
    private val SHA256 = Regex("[0-9a-f]{64}")
    private val RESOURCE = Regex("ic_ph_[a-z0-9_]+")
    private val ASSET = Regex("assets/(?:fill|regular)/[a-z0-9-]+\\.svg")
    private val TINT = Regex("@color/putio_[a-z0-9_]+")
    private val ICON_FIELDS = setOf("resDir", "resource", "asset", "sourceSha256", "outputSha256")

    data class Package(val name: String, val version: String, val tarball: String, val integrity: String)

    data class Icon(
        val resDir: String,
        val resource: String,
        val asset: String,
        val sourceSha256: String,
        val outputSha256: String,
        val tint: String? = null,
    ) {
        val outputPath: String get() = "$resDir/drawable/$resource.xml"
    }

    data class Lock(val pkg: Package, val icons: List<Icon>)

    fun parseLock(json: String): Lock {
        val document = try {
            Json.parseToJsonElement(json)
        } catch (error: SerializationException) {
            fail("cannot read design/phosphor-icons.lock.json: ${error.message}")
        }
        LockJson.duplicateKey(json)?.let { fail("lock contains duplicate key '$it'") }
        val root = document.objectOrFail("lock")
        val schemaVersion = root["schemaVersion"] as? JsonPrimitive
        if (root.keys != setOf("schemaVersion", "package", "icons") ||
            schemaVersion == null || schemaVersion.isString || schemaVersion.content != "1"
        ) {
            fail("lock must use schemaVersion 1 with package and icons fields")
        }

        val packageValue = root.getValue("package").objectOrFail("package")
        if (packageValue.keys != setOf("name", "version", "tarball", "integrity")) {
            fail("package lock fields do not match the schema")
        }
        val pkg = Package(
            name = packageValue.string("name", "package.name"),
            version = packageValue.string("version", "package.version"),
            tarball = packageValue.string("tarball", "package.tarball"),
            integrity = packageValue.string("integrity", "package.integrity"),
        )
        val expectedTarball = "https://registry.npmjs.org/@phosphor-icons/core/-/core-${pkg.version}.tgz"
        if (pkg.name != PACKAGE_NAME || pkg.tarball != expectedTarball) {
            fail("package name or tarball does not match the locked Phosphor version")
        }
        if (!pkg.integrity.startsWith(INTEGRITY_PREFIX)) fail("package.integrity must use sha512 SRI")
        val integrityDigest = pkg.integrity.removePrefix(INTEGRITY_PREFIX)
        val decoded = try {
            if (integrityDigest.length % 4 != 0) throw IllegalArgumentException("incorrect padding")
            Base64.getDecoder().decode(integrityDigest)
        } catch (_: IllegalArgumentException) {
            fail("package.integrity must contain valid base64")
        }
        if (decoded.size != SHA512_BYTES || Base64.getEncoder().encodeToString(decoded) != integrityDigest) {
            fail("package.integrity must contain a canonical SHA-512 digest")
        }

        val iconsValue = root.getValue("icons") as? JsonArray
        if (iconsValue == null || iconsValue.isEmpty()) fail("icons must be a non-empty array")
        val seenOutputs = mutableSetOf<String>()
        val icons = iconsValue.mapIndexed { index, rawIcon ->
            val field = "icons[$index]"
            val iconValue = rawIcon.objectOrFail(field)
            if (iconValue.keys != ICON_FIELDS && iconValue.keys != ICON_FIELDS + "tint") {
                fail("$field fields do not match the schema")
            }
            val icon = Icon(
                resDir = iconValue.string("resDir", "$field.resDir"),
                resource = iconValue.string("resource", "$field.resource"),
                asset = iconValue.string("asset", "$field.asset"),
                sourceSha256 = iconValue.sha256("sourceSha256", "$field.sourceSha256"),
                outputSha256 = iconValue.sha256("outputSha256", "$field.outputSha256"),
                tint = if ("tint" in iconValue) iconValue.string("tint", "$field.tint") else null,
            )
            if (icon.tint != null && !TINT.matches(icon.tint)) {
                fail("$field.tint must be a generated @color/putio_* token")
            }
            if (icon.resDir !in RES_DIRS) fail("$field.resDir is unsupported")
            if (!RESOURCE.matches(icon.resource)) fail("$field.resource is not an Android Phosphor resource name")
            if (!ASSET.matches(icon.asset)) fail("$field.asset is not a supported Phosphor SVG path")
            if (!seenOutputs.add(icon.outputPath)) fail("duplicate output ${icon.outputPath}")
            icon
        }
        return Lock(pkg, icons)
    }

    fun drawablesByPath(root: File, drawables: Iterable<File>): Map<String, File> =
        drawables.filter(File::isFile).associateBy { it.relativeTo(root).invariantSeparatorsPath }

    fun staleDrawables(lock: Lock, drawables: Map<String, File>): List<String> {
        val expected = lock.icons.map(Icon::outputPath).toSet()
        return drawables.filter { (path, file) ->
            path !in expected && runCatching { GENERATED_MARKER in file.readText() }.getOrDefault(false)
        }.keys.sorted()
    }

    fun driftFailures(lock: Lock, drawables: Map<String, File>): List<String> {
        val failures = lock.icons.mapNotNull { icon ->
            val file = drawables[icon.outputPath] ?: return@mapNotNull "missing ${icon.outputPath}"
            if (digestEquals(sha256(file.readBytes()), icon.outputSha256)) null else "drifted ${icon.outputPath}"
        }
        return (failures + staleDrawables(lock, drawables).map { "stale $it" }).sorted()
    }

    fun check(lock: Lock, drawables: Map<String, File>): String {
        val failures = driftFailures(lock, drawables)
        if (failures.isNotEmpty()) fail("icon drift detected:\n  " + failures.joinToString("\n  "))
        return "Phosphor icon drift check passed (${lock.icons.size} drawables, ${lock.pkg.name}@${lock.pkg.version})"
    }

    fun verifyArchive(pkg: Package, archive: ByteArray) {
        val actual = Base64.getEncoder().encodeToString(MessageDigest.getInstance("SHA-512").digest(archive))
        if (!digestEquals(actual, pkg.integrity.removePrefix(INTEGRITY_PREFIX))) {
            fail("downloaded package does not match locked sha512 SRI")
        }
    }

    fun render(lock: Lock, assets: Map<String, ByteArray>): Map<String, ByteArray> =
        lock.icons.associate { icon ->
            val source = assets[icon.asset] ?: fail("locked package is missing ${icon.asset}")
            if (!digestEquals(sha256(source), icon.sourceSha256)) fail("${icon.asset} does not match its locked SHA-256")
            val output = renderDrawable(icon, lock.pkg.version, source)
            if (!digestEquals(sha256(output), icon.outputSha256)) {
                fail("generated ${icon.resource}.xml does not match its locked SHA-256")
            }
            icon.outputPath to output
        }

    fun renderDrawable(icon: Icon, version: String, svg: ByteArray): ByteArray {
        val paths = svgPaths(icon, svg)
        if (paths.isEmpty()) fail("${icon.asset} contains no path data")
        val body = paths.joinToString("\n") { path ->
            "    <path\n" +
                "        android:fillColor=\"#FF000000\"\n" +
                "        android:pathData=\"${escapeAttribute(path)}\" />"
        }
        val iconName = if (icon.tint != null) {
            icon.asset.substringAfterLast('/').removeSuffix(".svg")
        } else {
            icon.resource.removePrefix("ic_ph_").replace('_', '-')
        }
        val tint = icon.tint?.let { "\n    android:tint=\"$it\"" }.orEmpty()
        return (
            "<!-- Phosphor $iconName v$version (MIT). $GENERATED_MARKER -->\n" +
                "<vector xmlns:android=\"http://schemas.android.com/apk/res/android\"\n" +
                "    android:width=\"24dp\"\n" +
                "    android:height=\"24dp\"\n" +
                "    android:viewportWidth=\"256\"\n" +
                "    android:viewportHeight=\"256\"$tint>\n" +
                "$body\n" +
                "</vector>\n"
            ).toByteArray(Charsets.UTF_8)
    }

    fun sha256(bytes: ByteArray): String =
        MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { "%02x".format(it) }

    private fun svgPaths(icon: Icon, svg: ByteArray): List<String> {
        val factory = DocumentBuilderFactory.newInstance().apply {
            isNamespaceAware = true
            setFeature(XMLConstants.FEATURE_SECURE_PROCESSING, true)
            setFeature("http://xml.org/sax/features/external-general-entities", false)
            setFeature("http://xml.org/sax/features/external-parameter-entities", false)
            setFeature("http://apache.org/xml/features/nonvalidating/load-external-dtd", false)
        }
        val document = try {
            factory.newDocumentBuilder().parse(ByteArrayInputStream(svg))
        } catch (error: org.xml.sax.SAXException) {
            fail("${icon.asset} is invalid XML: ${error.message}")
        }
        val elements = document.getElementsByTagName("*")
        return (0 until elements.length).map { elements.item(it) as Element }
            .filter { (it.localName ?: it.tagName).endsWith("path") && it.hasAttribute("d") }
            .map { it.getAttribute("d") }
    }

    private fun escapeAttribute(value: String): String =
        value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\"", "&quot;")

    private fun digestEquals(actual: String, expected: String): Boolean =
        MessageDigest.isEqual(actual.toByteArray(), expected.toByteArray())

    private fun JsonElement.objectOrFail(field: String): JsonObject = this as? JsonObject ?: fail("$field must be an object")

    private fun JsonObject.string(key: String, field: String): String =
        (this[key] as? JsonPrimitive)?.takeIf { it.isString && it.content.isNotEmpty() }?.content
            ?: fail("$field must be a non-empty string")

    private fun JsonObject.sha256(key: String, field: String): String =
        string(key, field).also { if (!SHA256.matches(it)) fail("$field must be a lowercase SHA-256 digest") }

    private fun fail(message: String): Nothing = throw GradleException("Phosphor icons: $message")
}
